#!/usr/bin/env python3
"""
Generate src/font8x16.h from a TrueType font.

The console uses an 8x16 fixed cell, so this rasterises ASCII 0x20..0x7F at
the largest pixel size where every glyph of JetBrains Mono fits that cell
without clipping: 13 px, baseline at row 12. The result is a 1-bit table with
one byte per scanline and the most-significant bit on the left, matching what
src/console.c already expects.

Usage:
    python3 tools/make-font.py \
        --font /tmp/jbmono/JetBrainsMono-Regular.ttf \
        --out  src/font8x16.h

Requires Pillow. The font is not a build dependency: the generated header is
checked in, so `./build.sh` needs nothing but NASM, GCC, ld and python3.
"""

import argparse
import sys

try:
    from PIL import Image, ImageDraw, ImageFont
except ImportError:  # pragma: no cover - developer tool only
    sys.exit("error: Pillow is required (pip install pillow)")

CELL_W = 8
CELL_H = 16
FIRST = 0x20
LAST = 0x7F
BASELINE = 12
PIXEL_SIZE = 13
THRESHOLD = 128

BANNER = """/*
 * 8x16 bitmap font derived from {family}, ASCII 0x20..0x7F.
 *
 * Rasterised from {font_file} at {size} px with the baseline on row
 * {baseline}. Generated by tools/make-font.py; edit that script rather than
 * this file.
 *
 * {family} is Copyright 2020 The JetBrains Mono Project Authors
 * (https://github.com/JetBrains/JetBrainsMono) and is licensed under the SIL
 * Open Font License, Version 1.1. The full licence text is in
 * LICENSES/JetBrainsMono-OFL.txt. This bitmap is a derivative and carries the
 * same licence; it is not public domain.
 *
 * Each glyph is {cell_h} bytes, one byte per scanline, most-significant bit on
 * the left.
 */
"""


def rasterise(font_path, size, baseline, threshold):
    font = ImageFont.truetype(font_path, size)
    glyphs = []
    for codepoint in range(FIRST, LAST + 1):
        # The canvas is wider than a cell so an accidentally wide glyph is
        # visibly clipped rather than silently reflowed.
        image = Image.new("L", (CELL_W * 2, CELL_H + 8), 0)
        draw = ImageDraw.Draw(image)
        draw.text((0, baseline), chr(codepoint), font=font, fill=255,
                  anchor="ls")
        pixels = image.load()
        rows = []
        for y in range(CELL_H):
            bits = 0
            for x in range(CELL_W):
                if pixels[x, y] >= threshold:
                    bits |= 0x80 >> x
            rows.append(bits)
        glyphs.append(rows)
    return glyphs


def label(codepoint):
    char = chr(codepoint)
    if char == " ":
        return "space"
    return f"{char}"


def emit(glyphs, family, font_file):
    lines = [BANNER.format(
        family=family,
        font_file=font_file,
        size=PIXEL_SIZE,
        baseline=BASELINE,
        cell_h=CELL_H,
    )]
    lines.append("#ifndef FONT8X16_H")
    lines.append("#define FONT8X16_H")
    lines.append("")
    lines.append("static const unsigned char font8x16[96][16] = {")
    for index, rows in enumerate(glyphs):
        codepoint = FIRST + index
        body = ", ".join(f"0x{value:02X}" for value in rows)
        lines.append(f"    {{ {body} }}, /* 0x{codepoint:02X} {label(codepoint):<5} */")
    lines.append("};")
    lines.append("")
    lines.append("#endif")
    lines.append("")
    return "\n".join(lines)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--font", default="JetBrainsMono-Regular.ttf",
                        help="path to a TrueType/OpenType font "
                             "(default: JetBrainsMono-Regular.ttf)")
    parser.add_argument("--out", default="src/font8x16.h",
                        help="output header (default: src/font8x16.h)")
    parser.add_argument("--family", default="JetBrains Mono",
                        help="human-readable family name for the banner")
    parser.add_argument("--font-file", default="JetBrainsMono-Regular.ttf",
                        help="file name to mention in the banner")
    args = parser.parse_args()

    glyphs = rasterise(args.font, PIXEL_SIZE, BASELINE, THRESHOLD)
    header = emit(glyphs, args.family, args.font_file)
    with open(args.out, "w", encoding="utf-8") as handle:
        handle.write(header)
    print(f"wrote {args.out}: 96 glyphs, {PIXEL_SIZE}px, baseline {BASELINE}")


if __name__ == "__main__":
    main()
